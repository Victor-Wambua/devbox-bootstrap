# shellcheck shell=bash
# shellcheck disable=SC2034
# Backups: before devbox modifies a file it copies the original to
# ~/.devbox/backups/<timestamp>/files/<absolute path>. The directory is created
# lazily, so a run that changes no files leaves no backup directory behind.

backup_begin_run() {
  BACKUP_TS=$(date +%Y%m%d-%H%M%S)
  BACKUP_DIR=""
  BACKED_UP=$'\n'
}

# backup_dir_ensure -> sets BACKUP_DIR (call in the current shell, not in $(...))
backup_dir_ensure() {
  if [[ -z ${BACKUP_DIR:-} ]]; then
    local base="$HOME/.devbox/backups/$BACKUP_TS" n=1
    BACKUP_DIR=$base
    while [[ -e $BACKUP_DIR ]]; do
      n=$((n + 1))
      BACKUP_DIR="$base-$n"
    done
    mkdir -p "$BACKUP_DIR/files"
    log_line INFO "backup directory $BACKUP_DIR"
  fi
}

# backup_file PATH -> copies PATH once per run; records files that did not exist
backup_file() {
  local path=$1 dir dest
  [[ $BACKED_UP == *$'\n'"$path"$'\n'* ]] && return 0
  backup_dir_ensure
  dir=$BACKUP_DIR
  if [[ -e $path ]]; then
    dest="$dir/files/${path#/}"
    mkdir -p "$(dirname "$dest")"
    cp -p "$path" "$dest"
    printf 'saved\t%s\n' "$path" >>"$dir/INDEX"
  else
    printf 'created\t%s\n' "$path" >>"$dir/INDEX"
  fi
  BACKED_UP+="$path"$'\n'
  log_line INFO "backed up $path"
}

# backup_defaults_value DOMAIN KEY -> records the current value so it can be restored.
# Appends a ready-to-run line to <backup>/restore-defaults.sh.
backup_defaults_value() {
  local domain=$1 key=$2 dir cur typ flag
  backup_dir_ensure
  dir=$BACKUP_DIR
  local script="$dir/restore-defaults.sh"
  if [[ ! -f $script ]]; then
    {
      printf '#!/bin/bash\n'
      printf '# Restores the macOS defaults devbox changed in this run.\n'
      printf '# Generated by devbox; review before running.\n'
    } >"$script"
    chmod 755 "$script"
  fi
  if cur=$(defaults read "$domain" "$key" 2>/dev/null); then
    typ=$(defaults read-type "$domain" "$key" 2>/dev/null || true)
    case $typ in
      *boolean*)
        flag=-bool
        if [[ $cur == 1 ]]; then cur=true; else cur=false; fi
        ;;
      *integer*) flag=-int ;;
      *float*) flag=-float ;;
      *string*) flag=-string ;;
      *) flag="" ;;
    esac
    if [[ -n $flag ]]; then
      printf 'defaults write %q %q %s %q\n' "$domain" "$key" "$flag" "$cur" >>"$script"
    else
      printf '# %s %s had a non-scalar value (%s); not restorable here\n' "$domain" "$key" "${typ:-unknown type}" >>"$script"
    fi
    printf 'saved\tdefaults:%s:%s\t%s\n' "$domain" "$key" "$cur" >>"$dir/INDEX"
  else
    printf 'defaults delete %q %q\n' "$domain" "$key" >>"$script"
    printf 'unset\tdefaults:%s:%s\n' "$domain" "$key" >>"$dir/INDEX"
  fi
}
